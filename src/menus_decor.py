from storage import ds

class DynamicAscii:
    """Sprytna klasa udająca string, która dynamicznie zwraca język w momencie jej wyświetlania."""
    def __init__(self, pl_art, en_art):
        self.pl_art = pl_art
        self.en_art = en_art
        
    @property
    def current(self):
        return self.en_art if ds.settings.get("language", "pl") == "en" else self.pl_art
        
    def __str__(self):
        return self.current
        
    def __add__(self, other):
        return self.current + str(other)
        
    def __radd__(self, other):
        return str(other) + self.current
        
    def __getattr__(self, name):
        # Przekazuje metody stringa (np. .splitlines() czy .startswith()) bezpośrednio do obecnego tekstu
        return getattr(self.current, name)


